import asyncio, json, pathlib
ROOT=pathlib.Path(__file__).resolve().parent.parent
URL=ROOT.joinpath("index.html").as_uri()
CAPS=ROOT/"tests"/"capturas"; CAPS.mkdir(exist_ok=True)
from playwright.async_api import async_playwright
R={}
def ok(k,c,det=""): R[k]={"ok":bool(c),"det":det}; print(k,"OK" if c else "FAIL",det)
async def cap(pg,name):
    await pg.evaluate("document.querySelectorAll('.toast').forEach(e=>e.remove())")
    await pg.locator("#phone").screenshot(path=str(CAPS/f"{name}.png"))
async def main():
    async with async_playwright() as p:
        b=await p.chromium.launch()
        pg=await b.new_page(viewport={"width":440,"height":900},device_scale_factor=2)
        errs=[]; pg.on("pageerror",lambda e:errs.append(str(e)))
        await pg.goto(URL)
        await cap(pg,"01_acceso")
        # CP-08 validación
        await pg.click(".btn:has-text('Ingresar')")
        e1=await pg.locator("text=Ingresá un correo").count(); e2=await pg.locator("text=al menos 6").count()
        await pg.fill("#f-mail","abc"); await pg.fill("#f-pass","123"); await pg.click(".btn:has-text('Ingresar')")
        ok("CP-01 Validación de acceso (campos inválidos)", e1==1 and e2==1 and await pg.locator("text=Ingresá un correo").count()==1)
        await pg.click("text=Crear cuenta")
        await pg.click(".btn:has-text('Crear cuenta')")
        await cap(pg,"01b_registro_errores")
        await pg.fill("#f-name","Giovanni Sosa"); await pg.fill("#f-mail","giovanni@correo.com"); await pg.fill("#f-pass","secreto1"); await pg.select_option("#f-sport","Fútbol")
        await pg.click(".btn:has-text('Crear cuenta')")
        ok("CP-02 Registro y entrada al sistema", await pg.locator("text=Hola, Giovanni").count()==1)
        await cap(pg,"02_inicio")
        await pg.click("nav button:nth-child(2)"); await cap(pg,"03_canchas")
        await pg.click(".chip:has-text('Pádel')")
        cards=await pg.locator("#list .card").count()
        names=await pg.locator("#list .card b").all_inner_texts()
        ok("CP-03 Filtro por deporte", cards==2, str(names))
        await pg.fill("#q","sajonia"); 
        ok("CP-04 Búsqueda por nombre o zona", await pg.locator("#list .card").count()==1)
        await pg.fill("#q",""); await pg.fill("#q","zzzz")
        ok("CP-05 Búsqueda sin resultados informa al usuario", await pg.locator("text=No hay canchas").count()==1)
        await pg.fill("#q","")
        await pg.click("#list .card >> nth=0"); await cap(pg,"04_detalle_cancha")
        await pg.click("text=Reservar horario")
        slot=pg.locator(".slot:not(.busy)").nth(1); h=await slot.inner_text(); await slot.click()
        await cap(pg,"05_reservar")
        await pg.click("text=Continuar al pago"); await cap(pg,"06_pago")
        await pg.click(".btn.or"); code=await pg.locator(".code").inner_text()
        ok("CP-06 Reserva y confirmación con código", code.startswith("JP-"), code)
        await cap(pg,"07_confirmacion")
        await pg.click("text=Volver al inicio"); await pg.click("nav button:nth-child(2)")
        await pg.click(".chip:has-text('Pádel')"); await pg.click("#list .card >> nth=0"); await pg.click("text=Reservar horario")
        ok("CP-07 Franja reservada queda bloqueada", await pg.locator(".slot.busy",has_text=h).count()==1, h)
        await pg.click("nav button:nth-child(3)"); await cap(pg,"08_torneos")
        await pg.click(".card >> nth=0")
        before=await pg.locator(".tag:has-text('equipos')").inner_text()
        await pg.click("text=Inscribir a mi equipo"); after=await pg.locator(".tag:has-text('equipos')").inner_text()
        ok("CP-08 Inscripción a torneo suma un equipo", before!=after, f"{before} -> {after}")
        await cap(pg,"09_torneo_fixture")
        await pg.click("text=Posiciones"); await cap(pg,"10_torneo_posiciones")
        await pg.click("nav button:nth-child(3)"); 
        await pg.click(".card >> nth=2")
        ok("CP-09 Torneo sin cupos deshabilita inscripción", await pg.locator("button:has-text('Sin cupos')[disabled]").count()==1)
        await pg.click("nav button:nth-child(4)"); await cap(pg,"11_comunidad")
        await pg.click(".btn.sm >> nth=0")
        ok("CP-10 Seguir jugador", await pg.locator("button:has-text('Siguiendo')").count()>=2)
        await pg.click("text=Partidos abiertos"); 
        await pg.click(".btn.sm >> nth=0"); ok("CP-11 Unirse a partido abierto", await pg.locator("button:has-text('Anotado')").count()==1)
        await cap(pg,"12_partidos_abiertos")
        await pg.click("text=Jugadores"); await pg.click(".mini-av >> nth=0"); await pg.click("text=Mensaje")
        await pg.fill("#mi","Hola, ¿jugamos el jueves?"); await pg.press("#mi","Enter"); await pg.wait_for_timeout(1300)
        ok("CP-12 Chat: envío y respuesta simulada", await pg.locator(".msg.me").count()==1 and await pg.locator(".msg").count()>=4)
        await cap(pg,"13_chat")
        await pg.click("#avatar"); await cap(pg,"14_perfil")
        ok("CP-13 Reserva visible en el perfil", await pg.locator("text=Código JP").count()==1)
        await pg.click("text=Cancelar reserva")
        ok("CP-14 Cancelar reserva", await pg.locator("text=Código JP").count()==0)
        await pg.click("nav button:nth-child(2)"); await pg.click(".chip:has-text('Pádel')"); await pg.click("#list .card >> nth=0"); await pg.click("text=Reservar horario")
        ok("CP-15 Cancelación libera la franja", await pg.locator(".slot.busy",has_text=h).count()==0)
        await pg.click("#avatar"); await pg.click("text=Cerrar sesión")
        ok("CP-16 Cierre de sesión vuelve al acceso", await pg.locator("text=Crear cuenta").count()>=1)
        pg2=await b.new_page(viewport={"width":360,"height":740})
        await pg2.goto(URL)
        ov=await pg2.evaluate("document.documentElement.scrollWidth<=window.innerWidth && document.querySelector('#phone').getBoundingClientRect().width<=360")
        ok("CP-17 Diseño responsivo a 360 px sin desbordes", ov)
        t=await pg2.evaluate("(()=>{const n=performance.getEntriesByType('navigation')[0];return Math.round(n.loadEventEnd)})()")
        R["load_ms"]=t; print("load_ms",t)
        print("ERRORS",errs); R["errors"]=errs
        json.dump(R,open(CAPS/"resultados.json","w"),ensure_ascii=False,indent=1)
        await b.close()
asyncio.run(main())
